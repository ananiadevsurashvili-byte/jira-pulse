/**
 * JiraPulse relay test harness (18 Nov 2026 review, verification duty).
 *
 * Builds a single combined module from the four relay sources
 * (shared.ts, auth.ts, desk.ts, relay-source.ts) with the esm.town blob
 * import replaced by an injected mock, so the REAL handler code runs in
 * Node against a fully mocked Jira/blob/email world.
 *
 * Run:  node --experimental-strip-types _tests/run-all.ts
 *       (Node 26 strips types natively; the flag is a no-op there)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', 'cors-relay');

/** Read one relay source and strip its imports/exports so the four files
 *  can be concatenated into one module scope (name collisions are checked
 *  by the loader — none exist today). */
function loadSource(name: string): string {
  let src = readFileSync(join(ROOT, name), 'utf8');
  /* drop import lines (blob URL + relative modules) */
  src = src.replace(/^import[\s\S]*?from\s+["'][^"']+["'];?\s*$/gm, '');
  /* strip top-level export keywords (keep `export default handler` handled
     by the caller via dropDefaultExport) */
  src = src.replace(/^export\s+(?=(const|let|var|function|async|type|class))/gm, '');
  return src;
}

const combinedParts = [
  '/* AUTO-GENERATED by _tests/harness.ts — do not edit; the real relay sources are the source of truth. */\n',
  '/* the mock blob store replaces https://esm.town/v/std/blob */\n',
  'const blob = globalThis.__jpBlobMock;\n',
  loadSource('shared.ts'),
  loadSource('auth.ts'),
  loadSource('desk.ts'),
  loadSource('relay-source.ts').replace(/^export\s+default\s+handler;?\s*$/gm, ''),
  /* test-visible exports */
  'export {\n' +
  '  handler,\n' +
  '  publishedProjects, storedCredsForHost, anonIssueGet, anonAttachmentGet,\n' +
  '  verifyGoogleIdToken, mintSession, authSession, dropSession, anonSessionGate,\n' +
  '  sessionsEnforced, setEnforceFlag, startEmailCode, verifyEmailCode,\n' +
  '  deliverEmailCode, isAdminEmail, orgEmailOk, ADMIN_EMAILS,\n' +
  '  anonIssueAllowed, sha256Hex, rateLimit, rateBuckets,\n' +
  '  CREDS_KEY, PUB_KEY, DESK_PROJECTS, DESK_EXTRA_KEY, ORG_EMAIL_DOMAIN,\n' +
  '  SESSIONS_KEY, EMAIL_CODES_KEY, ENFORCE_KEY, handleLgPing,\n' +
  '} as never;\n',
];

/* `as never` above would break ESM — write a plain export list instead */
combinedParts[combinedParts.length - 1] =
  'export {\n' +
  '  handler,\n' +
  '  publishedProjects, storedCredsForHost, anonIssueGet, anonAttachmentGet,\n' +
  '  verifyGoogleIdToken, mintSession, authSession, dropSession, anonSessionGate,\n' +
  '  sessionsEnforced, setEnforceFlag, startEmailCode, verifyEmailCode,\n' +
  '  deliverEmailCode, isAdminEmail, orgEmailOk, ADMIN_EMAILS,\n' +
  '  anonIssueAllowed, sha256Hex, rateLimit, rateBuckets, _pubProjectsCache,\n' +
  '  CREDS_KEY, PUB_KEY, DESK_PROJECTS, DESK_EXTRA_KEY, ORG_EMAIL_DOMAIN,\n' +
  '  SESSIONS_KEY, EMAIL_CODES_KEY, ENFORCE_KEY, handleLgPing,\n' +
  '};\n';

const OUT = join(HERE, '_combined.ts');
mkdirSync(HERE, { recursive: true });
writeFileSync(OUT, combinedParts.join('\n'));
console.log('[harness] combined module written to _tests/_combined.ts');
